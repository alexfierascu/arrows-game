// Downloads the "List of Dirty, Naughty, Obscene, and Otherwise Bad Words" and writes it to
// src/ldnoobw.js in the form the name filter uses. Run it to pick up changes to the list:
//   node scripts/update-ldnoobw.mjs
// Source: https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words (CC BY 4.0)

import { writeFile } from "node:fs/promises";
import { wordsOf } from "../src/profanity.js";

const SOURCE = "https://raw.githubusercontent.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words/master/";
const LANGUAGES = [
  "ar", "cs", "da", "de", "en", "eo", "es", "fa", "fi", "fil", "fr", "fr-CA-u-sd-caqc", "hi", "hu", "it", "ja",
  "kab", "ko", "nl", "no", "pl", "pt", "ru", "sv", "th", "tlh", "tr", "zh",
];
// Shorter entries would stop too many ordinary names. Scripts without an alphabet say more per character.
const MIN_LETTERS = 3, MIN_CHARACTERS = 2;
const ALPHABET = /^[\p{Script=Latin}\p{Script=Cyrillic}\p{Script=Greek}]+$/u;

/** One line of a list as a filter entry: its words joined, or null when it cannot be used. */
function toEntry(line) {
  if (/\d/.test(line)) return null; // "2g1c": the digits are part of the word, not look-alike letters
  const entry = wordsOf(line).join(""), length = [...entry].length;
  return length >= (ALPHABET.test(entry) ? MIN_LETTERS : MIN_CHARACTERS) ? entry : null;
}

const lists = {}, skipped = [];
for (const language of LANGUAGES) {
  const response = await fetch(SOURCE + language);
  if (!response.ok) throw new Error(`${language}: HTTP ${response.status}`);
  const entries = new Set();
  for (const line of (await response.text()).split("\n").map((l) => l.trim()).filter(Boolean)) {
    const entry = toEntry(line);
    if (entry) entries.add(entry); else skipped.push(`${language}:${line}`);
  }
  lists[language] = [...entries].join(" ");
  console.log(language, entries.size);
}
console.log("skipped (too short or with digits):", skipped.join("  "));

const header = `// Generated by scripts/update-ldnoobw.mjs. Do not edit by hand.
// The "List of Dirty, Naughty, Obscene, and Otherwise Bad Words" by LDNOOBW, one entry per word or
// joined phrase, lowercase without accents. Creative Commons Attribution 4.0:
// https://github.com/LDNOOBW/List-of-Dirty-Naughty-Obscene-and-Otherwise-Bad-Words
`;
const body = Object.entries(lists).map(([language, words]) => `  ${JSON.stringify(language)}: ${JSON.stringify(words)},`).join("\n");
await writeFile(new URL("../src/ldnoobw.js", import.meta.url), `${header}export default {\n${body}\n};\n`);
